#!/usr/bin/env node
/**
 * Write `open-props.css` (the design-system base values) into a public vendor
 * dir. Run by postinstall for dev (src/web/public/vendor, gitignored), by
 * prepare-test-vendor.mjs for the mobile suite, and by build.mjs for prod
 * (dist/web/public/vendor).
 *
 * Only the files that define custom properties are taken (sizes, fonts,
 * borders, easings, shadows, zindex), never normalize.css or buttons.css:
 * those restyle bare elements and would fight the existing stylesheets. Each
 * input only declares variables on `:where(html)`, and the bundle wraps them in
 * `@layer openprops`, the lowest layer, so styles.css (unlayered) always wins
 * and loading this file cannot change a pixel by itself. Colors are not taken:
 * UI color stays in the skins.
 *
 * `open-props` is pinned exactly in package.json; the layer order statement
 * here must match the one at the top of src/web/public/css/tokens.css.
 */

import { createRequire } from 'node:module';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';

const require = createRequire(import.meta.url);
const outputDir = resolve(process.argv[2] || join(import.meta.dirname, '..', 'src', 'web', 'public', 'vendor'));
const packageDir = dirname(require.resolve('open-props/package.json'));
const { version } = JSON.parse(readFileSync(join(packageDir, 'package.json'), 'utf8'));

export const OPEN_PROPS_FILES = ['sizes', 'fonts', 'borders', 'easings', 'shadows', 'zindex'];
export const LAYER_ORDER = '@layer openprops, tokens, skins, base, components, layout, features;';

const body = OPEN_PROPS_FILES.map((name) => readFileSync(join(packageDir, `${name}.min.css`), 'utf8').trim()).join('\n');
const css =
  `/* Open Props ${version} (MIT, https://open-props.style): ${OPEN_PROPS_FILES.join(', ')}. Generated by scripts/prepare-open-props.mjs. */\n` +
  `${LAYER_ORDER}\n` +
  `@layer openprops {\n${body}\n}\n`;

mkdirSync(outputDir, { recursive: true });
writeFileSync(join(outputDir, 'open-props.css'), css, 'utf8');
